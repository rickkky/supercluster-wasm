//! The fixture-pinned semantic-equivalence oracle (ticket 04's core
//! acceptance): Rust `get_clusters` membership matches JS supercluster's
//! captured membership, per Zoom Level, on `places.json` and the two seeded
//! 1k datasets.
//!
//! This is the query half's equivalent of ticket 03's count-match tests, but
//! one level stronger: it asserts the *membership* (which source Points end
//! up in which Cluster) is identical, not just the per-zoom count. Two
//! different clusterings can share a count; they cannot share a membership
//! multiset unless they are the same clustering.
//!
//! The fixtures are generated by `bench/oracle/capture-membership.js` (run
//! `pnpm oracle:capture` to regenerate). They capture JS supercluster's
//! `getClusters([-180, -90, 180, 90], z)` membership per zoom — the exact query
//! path the Rust `get_clusters` port mirrors — so both sides drop the same
//! antimeridian-wrapped points (clustered_synthetic emits a few lng > 180
//! points that project to x > 1.0 and fall outside the whole-world query box;
//! this is supercluster's own `getClusters` behavior, faithfully reproduced).
//!
//! The on-demand 1M/6M cross-diff (option B) lives in
//! `bench/oracle/oracle-1m-rust.js` and is run manually, not in CI — parallel
//! to the JS-vs-JS `oracle-1m.js`.

mod common;

use supercluster::oracle::MembershipFixture;
use supercluster::supercluster::Supercluster;

/// The whole-world query's membership must partition the *queryable* source
/// points — every geometry-bearing Point whose projected coord lies in
/// `[0, 1]` belongs to exactly one top-level membership. Antimeridian-wrapped
/// points (x > 1.0) are outside the whole-world box and are excluded from the
/// partition; both Rust and the JS fixture drop the same ones, so the
/// membership multiset still matches.
fn assert_partition(index: &Supercluster, zoom: i32, fixture: &MembershipFixture) {
    let memberships = index.extract_membership(zoom);
    let mut seen = std::collections::HashSet::new();
    let mut total = 0usize;
    for m in &memberships {
        for &id in m {
            assert!(
                seen.insert(id),
                "zoom {zoom}: point {id} appears in two clusters"
            );
            total += 1;
        }
    }
    // The partition covers the queryable subset: geometry-bearing minus the
    // antimeridian-wrapped points the whole-world query drops. The fixture's
    // own membership is the ground truth for that count (it drops the same
    // points), so compare against it rather than against `geometry_bearing`.
    let fixture_total: usize = fixture
        .membership
        .get(&zoom)
        .map(|ms| ms.iter().map(|m| m.len()).sum())
        .unwrap_or(0);
    assert_eq!(
        total, fixture_total,
        "zoom {zoom}: Rust partition covers {total} points, fixture covers {fixture_total}"
    );
}

/// Run the full membership diff for one corpus: build the Rust index over the
/// same points the fixture was captured from, diff against the fixture, assert
/// zero differences. Prints the first differing zoom's details on failure.
fn assert_membership_matches(corpus: &str, points: Vec<supercluster::feature::PointFeature>) {
    let fixture = common::load_membership_fixture(corpus);
    let index = Supercluster::load(points, common::oracle_options());

    // Sanity: the fixture's options match the oracle's.
    assert_eq!(fixture.max_zoom, common::oracle_options().max_zoom);

    let diff = index.diff_membership_vs_fixture(&fixture);
    assert_eq!(
        diff.total_differences, 0,
        "{corpus}: membership differs from JS supercluster fixture — {} differences across {} zoom(s): {:#?}",
        diff.total_differences,
        diff.differences.len(),
        diff.differences,
    );

    // The partition property must also hold per zoom (mirrors the JS
    // `extractMembership: memberships partition the source Points` tests).
    for &z in &fixture.zooms {
        assert_partition(&index, z, &fixture);
    }
}

#[test]
fn places_json_membership_matches_js_supercluster() {
    // The oracle seed corpus (163 features, one geometry:null). Rust
    // `get_clusters` membership must be identical to JS supercluster's at
    // every zoom [0, 6]. This is the ticket's primary acceptance: "Oracle
    // confirms Cluster membership per Zoom Level matches JS supercluster on
    // places.json."
    assert_membership_matches("places", common::load_places());
}

#[test]
fn uniform_1000_seed_42_membership_matches_js_supercluster() {
    // The seeded 1k uniform set — the same (n, seed) the JS oracle
    // self-verifies against. Membership must match at every zoom.
    assert_membership_matches("uniform-1000-42", common::uniform_random(1000, 42));
}

#[test]
fn clustered_1000_seed_42_membership_matches_js_supercluster() {
    // The seeded 1k clustered set, which includes antimeridian-wrapped points
    // (lng > 180 → x > 1.0). Both Rust and the JS fixture drop these from the
    // whole-world query identically, so the membership multiset still matches
    // — this is the case that proves the antimeridian handling is faithful to
    // supercluster's own `getClusters`, not just internally consistent.
    assert_membership_matches("clustered-1000-42", common::clustered_synthetic(1000, 42));
}

#[test]
fn fixture_entry_counts_match_rust_lattice_counts() {
    // A consistency cross-check: the fixture's per-zoom membership *list
    // length* must equal the Rust lattice's top-level entry count at every
    // zoom (for corpora with no antimeridian-wrapped points — places.json and
    // uniform). For clustered, the fixture length is the queryable count
    // (lattice count minus wrapped-only top-level entries), so it is <= the
    // lattice count; assert the non-wrapped corpora match exactly here.
    for corpus in ["places", "uniform-1000-42"] {
        let fixture = common::load_membership_fixture(corpus);
        let points = match corpus {
            "places" => common::load_places(),
            "uniform-1000-42" => common::uniform_random(1000, 42),
            _ => unreachable!(),
        };
        let index = Supercluster::load(points, common::oracle_options());
        for &z in &fixture.zooms {
            let fixture_n = fixture.membership.get(&z).map(|m| m.len()).unwrap_or(0);
            let lattice_n = index.stack.get(z).map(|l| l.len()).unwrap_or(0);
            assert_eq!(
                fixture_n, lattice_n,
                "{corpus} zoom {z}: fixture membership count {fixture_n} != lattice count {lattice_n}"
            );
        }
    }
}

#[test]
fn anti_tautology_rust_vs_different_radius_fixture_diff_is_nonzero() {
    // The oracle would be worthless if it always returned zero. Building Rust
    // with a different radius than the fixture (which used the default 40)
    // MUST surface non-zero membership differences — the anti-tautology guard
    // for the fixture-pinned oracle, mirroring the JS self-verify's
    // "different radius is detected as non-zero."
    let fixture = common::load_membership_fixture("places");
    let points = common::load_places();
    let index = Supercluster::load(
        points,
        supercluster::options::Options {
            radius: 100.0,
            ..common::oracle_options()
        },
    );
    let diff = index.diff_membership_vs_fixture(&fixture);
    assert!(
        diff.total_differences > 0,
        "different radius must yield non-zero membership diff, got {}",
        diff.total_differences
    );
}
